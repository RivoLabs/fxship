# Both server folders: fxship.cfg, instance.cfg, secrets.cfg, server.cfg, txAdmin settings and the
# systemd units. Nothing here restarts a server that is up.
# shellcheck shell=bash

# managed FILE: replaces the block between the fxship markers (or adds it), keeping the owner's lines.
managed() {
  local f=$1 block tmp
  block=$(cat)
  tmp=$(mktemp)
  if [ -f "$f" ]; then
    awk '/^# BEGIN fxship/{skip=1; next} /^# END fxship/{skip=0; next} !skip' "$f" >"$tmp"
  fi
  { echo "# BEGIN fxship (managed by the installer: re-run it to change these)"; echo "$block"; echo "# END fxship"; cat "$tmp"; } >"$f.new"
  mv "$f.new" "$f"; rm -f "$tmp"
}

instance_cfg() { # instance_cfg prod|dev
  local i=$1 ip port name
  if [ "$i" = prod ]; then ip=$PROD_IP port=$PROD_GAME_PORT name=$BRAND_NAME; else ip=$DEV_IP port=$DEV_GAME_PORT name="$BRAND_NAME [DEV]"; fi
  if [ "$TOPOLOGY" = two-ip ]; then
    echo "endpoint_add_tcp \"$ip:$port\""
    echo "endpoint_add_udp \"$ip:$port\""
    echo "set sv_listingIpOverride \"$ip\""
  else
    echo "endpoint_add_tcp \"0.0.0.0:$port\""
    echo "endpoint_add_udp \"0.0.0.0:$port\""
  fi
  echo "sv_hostname \"$name\""
  echo "sets fxship_instance \"$i\""
  # Dev stays off the public server list.
  [ "$i" = dev ] && echo 'set sv_master1 ""'
  return 0
}

secrets_cfg() { # secrets_cfg prod|dev
  local i=$1 key db
  if [ "$i" = prod ]; then key=$PROD_LICENSE_KEY; else key=${DEV_LICENSE_KEY:-$PROD_LICENSE_KEY}; fi
  echo "sv_licenseKey \"$key\""
  if is_true "${DB_INSTALL:-}"; then
    if [ "$i" = prod ]; then db="$DB_PROD_USER:$DB_PROD_PASSWORD@127.0.0.1:3306/$DB_PROD_NAME"; else db="$DB_DEV_USER:$DB_DEV_PASSWORD@127.0.0.1:3306/$DB_DEV_NAME"; fi
    echo "set mysql_connection_string \"mysql://$db?charset=utf8mb4\""
  fi
}

# import_cfgs DATA: copies server.cfg and the .cfg files beside it from CFG_SOURCE, once.
import_cfgs() {
  local data=$1 src
  [ "$REPO_LAYOUT" = server-data ] && return 0
  [ -f "$data/server.cfg" ] && return 0
  case $CFG_SOURCE in
    starter) src=$BUNDLE/examples/resources-layout ;;
    repo) src=$(mktemp -d); as_fivem git --git-dir "$FIVEM_ROOT/repo.git" archive "origin/$REPO_BRANCH" 2>/dev/null | tar -x -C "$src" --wildcards '*.cfg' 2>/dev/null || true ;;
    *) src=$CFG_SOURCE ;;
  esac
  find "$src" -maxdepth 1 -name '*.cfg' ! -name secrets.cfg ! -name fxship.cfg ! -name instance.cfg -exec cp --update=none -t "$data" {} +
  [ -f "$src/myLogo.png" ] && cp --update=none "$src/myLogo.png" "$data/"
  [ -f "$data/server.cfg" ] || die "no server.cfg came from $CFG_SOURCE"
  # Values that belong to prod alone move out of the shared server.cfg into prod's secrets.
  grep -iE '^\s*(set\s+)?sv_tebexSecret\b' "$data/server.cfg" >"$data/.tebex" 2>/dev/null || true
}

txadmin_json() { # txadmin_json prod|dev data onesync
  local i=$1 data=$2 onesync=${3:-} f=$FIVEM_ROOT/$1/txData/default/config.json sched
  if [ "$i" = prod ]; then sched=$(jq -cn --arg s "$RESTART_TIMES" '$s | split(",")'); else sched='[]'; fi
  if [ -f "$f" ]; then
    # Keep everything the owner set in txAdmin; only fxship's three settings are enforced, and
    # onesync is only filled in if txAdmin has none yet.
    jq --arg d "$data/" --argjson s "$sched" --arg o "$onesync" \
      '.server.dataPath=$d | .server.cfgPath="fxship.cfg" | .restarter.schedule=$s | if $o != "" then .server.onesync //= $o else . end' "$f" >"$f.new" && mv "$f.new" "$f"
  else
    local name=$BRAND_NAME; [ "$i" = dev ] && name="$BRAND_NAME [DEV]"
    jq -n --arg n "$name" --arg d "$data/" --argjson s "$sched" --arg o "$onesync" \
      '{version: 2, general: {serverName: $n}, server: ({dataPath: $d, cfgPath: "fxship.cfg", autoStart: true} + (if $o != "" then {onesync: $o} else {} end)), restarter: {schedule: $s}}' >"$f"
  fi
}

step_servers() {
  step "Game servers"
  install -m 644 "$BUNDLE/installer/linux/files/fivem@.service" /etc/systemd/system/fivem@.service
  sed -i "s#/srv/fivem#$FIVEM_ROOT#" /etc/systemd/system/fivem@.service
  local i servers=(prod)
  is_true "$DEV_ENABLED" && servers+=(dev)
  for i in "${servers[@]}"; do
    local base=$FIVEM_ROOT/$i data=$FIVEM_ROOT/$i/server-data
    install -d -o fivem -g fivem "$base" "$data" "$base/txData" "$base/txData/default"
    import_cfgs "$data"

    instance_cfg "$i" | managed "$data/instance.cfg"
    secrets_cfg "$i" | managed "$data/secrets.cfg"
    if [ "$i" = prod ] && [ -s "$data/.tebex" ] && ! grep -qi tebexSecret "$data/secrets.cfg"; then cat "$data/.tebex" >>"$data/secrets.cfg"; fi
    rm -f "$data/.tebex"
    cat >"$data/fxship.cfg" <<CFG
# Generated by fxship: txAdmin starts the server with this file. Do not edit it. Edit server.cfg,
# or instance.cfg and secrets.cfg for settings that differ between prod and dev.
exec instance.cfg
exec secrets.cfg
exec server.fxship.cfg
CFG
    local onesync=""
    if [ -f "$data/server.cfg" ]; then onesync=$(fxship cfg-sanitize "$data" | awk '$1 == "onesync" {print $2}'); fi
    chown fivem:fivem "$data"/*.cfg; chmod 600 "$data/secrets.cfg"; chmod 644 "$data/fxship.cfg" "$data/instance.cfg"
    [ "$i" = dev ] && find "$data" -maxdepth 1 -name '*.cfg' ! -name secrets.cfg ! -name fxship.cfg ! -name 'server.fxship.cfg' ! -name instance.cfg -exec chmod 664 {} +

    local port hash
    port=$([ "$i" = prod ] && echo 40120 || echo 40130)
    hash=$(htpasswd -bnBC 11 "" "$( [ "$i" = prod ] && echo "$PROD_TX_PASSWORD" || echo "$DEV_TX_PASSWORD")" | tr -d ':\n' | sed 's/^\$2y\$/$2b$/')
    umask 077
    cat >/etc/fivem/$i.env <<ENV
TXHOST_DATA_PATH=$base/txData
TXHOST_TXA_PORT=$port
TXHOST_PROVIDER_NAME=$BRAND_NAME
TXHOST_IGNORE_DEPRECATED_CONFIGS=true
TXHOST_DEFAULT_ACCOUNT=$TX_USER::$hash
ENV
    umask 022
    [ -n "${TS_NAME:-}" ] && echo "TXHOST_TXA_URL=http://$TS_NAME:$port" >>/etc/fivem/$i.env
    txadmin_json "$i" "$data" "$onesync"
    chown -R fivem:fivem "$base/txData"

    install -d /etc/systemd/system/fivem@$i.service.d
    if [ "$i" = dev ]; then
      local cores=${DEV_CPU_CORES:-2} mem=${DEV_MEMORY_MAX_MB:-4096}
      sed "s/@CPU_QUOTA@/$((cores * 100))%/; s/@MEMORY_HIGH@/$((mem * 7 / 8))M/; s/@MEMORY_MAX@/${mem}M/" \
        "$BUNDLE/installer/linux/files/fivem-dev.conf" >/etc/systemd/system/fivem@dev.service.d/limits.conf
    else
      install -m 644 "$BUNDLE/installer/linux/files/fivem-prod.conf" /etc/systemd/system/fivem@prod.service.d/limits.conf
    fi
    ok "$i: $data"
  done
  if ! is_true "$DEV_ENABLED"; then
    systemctl disable --now fivem@dev >/dev/null 2>&1 || true
    systemctl reset-failed fivem@dev >/dev/null 2>&1 || true
  fi
  systemctl daemon-reload
  for i in "${servers[@]}"; do systemctl enable "fivem@$i" >/dev/null 2>&1; done
}

# start_servers runs after the agent has put the repo in place. Servers already up are left alone.
start_servers() {
  step "Starting servers"
  local i servers=(prod) port url
  is_true "$DEV_ENABLED" && servers+=(dev)
  # server-data layout: server.cfg arrived with the repo; prod's Tebex secret moves to its secrets.
  local data=$FIVEM_ROOT/prod/server-data
  if [ -f "$data/server.cfg" ] && ! grep -qi tebexSecret "$data/secrets.cfg"; then
    grep -iE '^\s*(set\s+)?sv_tebexSecret\b' "$data/server.cfg" >>"$data/secrets.cfg" || true
  fi
  for i in "${servers[@]}"; do
    # server-data layout: server.cfg only arrived with the first checkout, so its onesync mode
    # reaches txAdmin here (only while txAdmin has none of its own).
    local d=$FIVEM_ROOT/$i/server-data onesync tx
    tx=$FIVEM_ROOT/$i/txData/default/config.json
    if [ -f "$d/server.cfg" ] && [ -f "$tx" ]; then
      onesync=$(fxship cfg-sanitize "$d" | awk '$1 == "onesync" {print $2}')
      if [ -n "$onesync" ]; then
        jq --arg o "$onesync" '.server.onesync //= $o' "$tx" >"$tx.new" && mv "$tx.new" "$tx" && chown fivem:fivem "$tx"
      fi
    fi
    port=$([ "$i" = prod ] && echo "$PROD_GAME_PORT" || echo "$DEV_GAME_PORT")
    # Two-ip servers listen on their own IP only, so ask where fxship asks.
    url=$([ "$i" = prod ] && echo "$PROD_INFO_URL" || echo "$DEV_INFO_URL")
    if systemctl is-active --quiet "fivem@$i"; then
      ok "$i is already running (changes apply at its next restart)"
      continue
    fi
    systemctl start "fivem@$i"
    info "waiting for $i to come up on port $port..."
    local _
    for _ in $(seq 1 100); do game_up "$url" && break; sleep 3; done
    if game_up "$url"; then ok "$i is up"; else warn "$i didn't answer within 5 minutes: check txAdmin ($( [ "$i" = prod ] && echo 40120 || echo 40130)) or journalctl -u fivem@$i"; fi
  done
}
