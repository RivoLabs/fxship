package main

// Each server boots fxship.cfg, which the installer writes:
//
//	exec instance.cfg       per server: endpoints, hostname, listing IP (not in git)
//	exec secrets.cfg        per server: license key, database, Tebex (not in git)
//	exec server.fxship.cfg  the owner's server.cfg with the lines above taken out
//
// server.fxship.cfg is regenerated whenever server.cfg changes, so owners keep editing the server.cfg
// they already have. Lines that would make dev bind prod's port, use prod's database or take prod's
// store purchases never reach a server from there.

import (
	"bufio"
	"bytes"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"sync"
)

// reInstanceLine matches the commands that must differ per server, must stay out of git, or belong
// to txAdmin. Group 1 is the command or convar name.
var reInstanceLine = regexp.MustCompile(`(?i)^\s*(?:(?:set|sets|setr)\s+)?(endpoint_add_tcp|endpoint_add_udp|sv_licensekey|sv_hostname|sv_listingipoverride|sv_master1|mysql_connection_string|rcon_password|sv_tebexsecret|onesync)\b`)

// cfgNames spells each name the way the FiveM docs do, and says where its value comes from instead.
var cfgNames = map[string][2]string{
	"endpoint_add_tcp":        {"endpoint_add_tcp", "set per server in instance.cfg"},
	"endpoint_add_udp":        {"endpoint_add_udp", "set per server in instance.cfg"},
	"sv_hostname":             {"sv_hostname", "set per server in instance.cfg"},
	"sv_listingipoverride":    {"sv_listingIpOverride", "set per server in instance.cfg"},
	"sv_master1":              {"sv_master1", "set per server in instance.cfg"},
	"sv_licensekey":           {"sv_licenseKey", "a secret: set per server in secrets.cfg"},
	"mysql_connection_string": {"mysql_connection_string", "a secret: set per server in secrets.cfg"},
	"rcon_password":           {"rcon_password", "a secret: put it in secrets.cfg if you use rcon"},
	"sv_tebexsecret":          {"sv_tebexSecret", "a secret: prod's is in its secrets.cfg"},
	"onesync":                 {"onesync", "a txAdmin setting (Settings > FXServer)"},
}

// SanitizeCfg returns src with per-server, secret and txAdmin-owned lines commented out, plus the
// names it took out.
func SanitizeCfg(src []byte) ([]byte, []string) {
	var out bytes.Buffer
	var removed []string
	seen := map[string]bool{}
	out.WriteString("# Generated by fxship from server.cfg. Do not edit: edit server.cfg, instance.cfg or secrets.cfg.\n")
	sc := bufio.NewScanner(bytes.NewReader(src))
	sc.Buffer(make([]byte, 64<<10), 4<<20)
	for sc.Scan() {
		line := sc.Text()
		if m := reInstanceLine.FindStringSubmatch(line); m != nil {
			n := cfgNames[strings.ToLower(m[1])]
			fmt.Fprintf(&out, "# [fxship] %s is %s\n", n[0], n[1])
			if !seen[n[0]] {
				seen[n[0]] = true
				removed = append(removed, n[0])
			}
			continue
		}
		out.WriteString(line)
		out.WriteByte('\n')
	}
	return out.Bytes(), removed
}

// CfgOneSync returns the onesync mode a server.cfg asks for (on, legacy or off), or "" if it doesn't
// set one. txAdmin owns the setting, so the installer passes it on.
func CfgOneSync(src []byte) string {
	mode := ""
	for _, line := range strings.Split(string(src), "\n") {
		f := strings.Fields(strings.ToLower(line))
		if len(f) >= 3 && (f[0] == "set" || f[0] == "setr" || f[0] == "sets") && f[1] == "onesync" {
			v := strings.Trim(f[2], `"`)
			switch v {
			case "on", "legacy", "off":
				mode = v
			case "true", "1":
				mode = "on"
			case "false", "0":
				mode = "off"
			}
		}
	}
	return mode
}

// cfgSync remembers what each server's server.cfg looked like when it was last sanitized.
type cfgSync struct {
	mu   sync.Mutex
	sigs map[string]string
}

var cfgState = &cfgSync{sigs: map[string]string{}}

// SyncCfg rewrites server.fxship.cfg in dataDir when server.cfg has changed since the last call.
// It reports whether it wrote anything.
func SyncCfg(dataDir string) (bool, error) {
	src := filepath.Join(dataDir, "server.cfg")
	dst := filepath.Join(dataDir, "server.fxship.cfg")
	fi, err := os.Stat(src)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}
	sig := fmt.Sprintf("%d:%d", fi.Size(), fi.ModTime().UnixNano())
	cfgState.mu.Lock()
	defer cfgState.mu.Unlock()
	if cfgState.sigs[dataDir] == sig {
		if _, err := os.Stat(dst); err == nil {
			return false, nil
		}
	}
	b, err := os.ReadFile(src)
	if err != nil {
		return false, err
	}
	clean, _ := SanitizeCfg(b)
	if old, err := os.ReadFile(dst); err == nil && bytes.Equal(old, clean) {
		cfgState.sigs[dataDir] = sig
		return false, nil
	}
	tmp := dst + ".tmp"
	if err := os.WriteFile(tmp, clean, 0o644); err != nil {
		return false, err
	}
	if err := os.Rename(tmp, dst); err != nil {
		return false, err
	}
	cfgState.sigs[dataDir] = sig
	return true, nil
}

func (a *Agent) syncCfg(t serverTarget) {
	if wrote, err := SyncCfg(t.ServerData); err != nil {
		log.Printf("%s: server.cfg: %v", t.Name, err)
	} else if wrote {
		log.Printf("%s: server.fxship.cfg regenerated from server.cfg", t.Name)
	}
}

func (a *Agent) targets() []serverTarget {
	if a.cfg.DevEnabled {
		return []serverTarget{a.cfg.Prod, a.cfg.Dev}
	}
	return []serverTarget{a.cfg.Prod}
}
